# Ejercicio 10: Conversor de Temperatura

# Pedimos la temperatura en grados Celsius
celsius = float(input("Ingrese la temperatura en ºC: "))

# Convertimos de Celsius a Fahrenheit
fahrenheit = (celsius * 9 / 5) + 32

# Mostramos el resultado
print(celsius, "ºC equivalen a", fahrenheit, "ºF")
